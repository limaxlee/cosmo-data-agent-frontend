"use client";

import { useRouter } from "next/navigation";
import { useUser } from "@/providers/user-provider";
import { Input } from "@/components/ui/input";
import { Button } from "@/components/ui/button";
import { copyText } from "@/lib/clipboard";
import { ScrollArea } from "@/components/ui/scroll-area";
import { useState, useEffect, useCallback, useRef } from "react";
import { SessionStorage } from "@/lib/session-api";
import { writeDraft } from "@/lib/draft-storage";
import { ChatSession } from "@/lib/types";
import { Sheet, SheetContent, SheetTrigger } from "@/components/ui/sheet";
import { DataAgentWordmark } from "@/components/data-agent-wordmark";
import { APP_TITLE } from "@/lib/app-title";
import Image from "next/image";
import diceIcon from "@/app/dice_icon.png";

import {
  Tooltip,
  TooltipContent,
  TooltipProvider,
  TooltipTrigger,
} from "@/components/ui/tooltip";
import {
  DropdownMenu,
  DropdownMenuContent,
  DropdownMenuItem,
  DropdownMenuTrigger,
} from "@/components/ui/dropdown-menu";
import {
  Plus,
  Trash2,
  Copy,
  Search,
  MessageSquare,
  MoreVertical,
  PanelLeft,
  Pencil,
  LogOut,
} from "lucide-react";

const SIDEBAR_COLLAPSED_KEY = "sidebar_collapsed";

/**
 * Collapsed state has to outlive the component. /chat/new and /chat/[sessionId]
 * each render their own ChatView, so navigating between them remounts the
 * sidebar and would otherwise reset it to expanded. Null means "not toggled yet
 * this page load", in which case the stored preference is used.
 */
let lastCollapsed: boolean | null = null;

function readCollapsed(): boolean {
  if (lastCollapsed !== null) return lastCollapsed;
  if (typeof window === "undefined") return false;

  try {
    return localStorage.getItem(SIDEBAR_COLLAPSED_KEY) === "1";
  } catch {
    return false;
  }
}

interface SessionSidebarProps {
  currentSessionId: string | null;
  userId: string;
  onSessionSelect: (session: ChatSession | null) => void;
  onNewSession: () => void;
  /** Reports the open chat title whenever the poll below picks up a change. */
  onCurrentSessionTitleChange?: (title: string) => void;
  className?: string;
}

export function SessionSidebar({
  currentSessionId,
  onSessionSelect,
  onNewSession,
  onCurrentSessionTitleChange,
  className = "",
}: SessionSidebarProps) {
  const { userId, clearUserId } = useUser();
  const [sessions, setSessions] = useState<ChatSession[]>([]);
  const [isLoading, setIsLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const [searchQuery, setSearchQuery] = useState("");
  const [debouncedSearchQuery, setDebouncedSearchQuery] = useState("");
  const [isCollapsed, setIsCollapsed] = useState(readCollapsed);
  const [isMobileOpen, setIsMobileOpen] = useState(false);
  const [isSearchActive, setIsSearchActive] = useState(false);
  const [openMenuId, setOpenMenuId] = useState<string | null>(null);
  const [renamingId, setRenamingId] = useState<string | null>(null);
  const [renameValue, setRenameValue] = useState("");

  /**
   * Enter and Escape both leave the rename box through blur, so the save lives
   * in one place and can't fire twice. This flag is what tells the two apart.
   */
  const renameAbandonedRef = useRef(false);

  /**
   * Radix hands focus back to the trigger when a menu closes, which would pull
   * it straight out of the rename box we just opened. Set only by Rename, so
   * Copy and Delete keep their normal focus behaviour.
   */
  const renameStartedRef = useRef(false);

  const renameInputRef = useRef<HTMLInputElement | null>(null);

  const router = useRouter();

  const loadSessions = useCallback(async () => {
    if (!userId) return;

    try {
      setError(null);
      const remote = await SessionStorage.listSessions(userId);
      setSessions(remote);
    } catch (e) {
      console.error("Error loading sessions:", e);
      setError("Couldn't load chats");
    } finally {
      setIsLoading(false);
    }
  }, [userId]);

  useEffect(() => {
    loadSessions();
    const interval = setInterval(loadSessions, 5000);
    return () => clearInterval(interval);
  }, [loadSessions]);

  // The poll is the only place a title generated by the backend after the
  // first message -- or renamed from another tab -- shows up, so the page gets
  // it from here for its document title.
  useEffect(() => {
    if (!currentSessionId) return;

    const current = sessions.find((s) => s.id === currentSessionId);

    if (current) onCurrentSessionTitleChange?.(current.title);
  }, [sessions, currentSessionId, onCurrentSessionTitleChange]);

  useEffect(() => {
    const timer = setTimeout(() => {
      setDebouncedSearchQuery(searchQuery);
    }, 150);
    return () => clearTimeout(timer);
  }, [searchQuery]);

  /* Windows-style rename: the whole title starts selected, ready to be typed
     over. One frame late on purpose -- the closing dropdown is still moving
     focus around as the box mounts, and a select done synchronously can be
     undone under it. Keyed on the id, so a refocus mid-edit doesn't re-select
     what the user already narrowed down. */
  useEffect(() => {
    if (!renamingId) return;

    const id = requestAnimationFrame(() => {
      const el = renameInputRef.current;

      if (!el) return;

      el.focus();
      el.select();
    });

    return () => cancelAnimationFrame(id);
  }, [renamingId]);

  const filteredSessions = sessions.filter((session) =>
    session.title.toLowerCase().includes(debouncedSearchQuery.toLowerCase()),
  );

  const handleSessionClick = (session: ChatSession) => {
    router.push(`/chat/${session.id}`);
    setIsMobileOpen(false);
  };

  const toggleCollapsed = () => {
    const next = !isCollapsed;

    lastCollapsed = next;
    setIsCollapsed(next);

    try {
      localStorage.setItem(SIDEBAR_COLLAPSED_KEY, next ? "1" : "0");
    } catch {
      // Storage blocked - the sidebar still works for this page load.
    }
  };

  const handleNewSession = () => {
    onNewSession();
    router.push("/chat/new");
    setIsMobileOpen(false);
  };

  const handleDeleteSession = async (
    e: React.MouseEvent,
    sessionId: string,
  ) => {
    e.stopPropagation();
    if (!userId) return;
    if (!confirm("Are you sure you want to delete this session?")) return;

    try {
      await SessionStorage.deleteSession(userId, sessionId);

      // The chat is gone; its unsent draft has nothing left to belong to.
      writeDraft(sessionId, "");

      const onThisSession =
        currentSessionId === sessionId ||
        (typeof window !== "undefined" &&
          window.location.pathname === `/chat/${sessionId}`);

      if (onThisSession) {
        onNewSession();
        router.push("/chat/new");
      }
      await loadSessions();
    } catch (err) {
      console.error("Failed to delete session:", err);
    }
  };

  const startRename = (e: React.MouseEvent, session: ChatSession) => {
    e.stopPropagation();
    renameAbandonedRef.current = false;
    renameStartedRef.current = true;
    setRenamingId(session.id);
    setRenameValue(session.title);
  };

  const handleRenameKeyDown = (e: React.KeyboardEvent<HTMLInputElement>) => {
    if (e.key === "Enter") {
      e.preventDefault();
      e.currentTarget.blur();
    } else if (e.key === "Escape") {
      e.preventDefault();
      renameAbandonedRef.current = true;
      e.currentTarget.blur();
    }
  };

  const handleRenameBlur = async (session: ChatSession) => {
    const abandoned = renameAbandonedRef.current;
    const title = renameValue.trim();

    renameAbandonedRef.current = false;
    setRenamingId(null);

    // Escape, an empty box, or a title that didn't change: nothing to send.
    if (abandoned || !userId || !title || title === session.title) return;

    // Show the new title straight away; loadSessions() below is the source of
    // truth, so a rejected rename reverts on its own.
    setSessions((prev) =>
      prev.map((s) => (s.id === session.id ? { ...s, title } : s)),
    );

    try {
      await SessionStorage.renameSession(userId, session.id, title);
    } catch (err) {
      console.error("Failed to rename session:", err);
    } finally {
      await loadSessions();
    }
  };

  const handleLogout = () => {
    setIsMobileOpen(false);
    clearUserId();
  };

  const userInitial = (userId ?? "").trim().charAt(0).toUpperCase();

  const handleCopy = async (e: React.MouseEvent, session: ChatSession) => {
    e.stopPropagation();
    try {
      await copyText(session.title);
    } catch (error) {
      console.error("Failed to copy to clipboard:", error);
    }
  };

  const SidebarContent = () => (
    <div className="flex flex-col h-full bg-card/95 backdrop-blur-sm">
      {/* Header */}
      <div className={isCollapsed ? "px-2 pt-2 pb-1" : "px-2 pt-2 pb-4"}>
        <div
          className={`flex items-center ${
            isCollapsed ? "justify-center mb-1" : "justify-between mb-4"
          }`}
        >
          {!isCollapsed && (
            /* The wordmark doubles as the home affordance. It runs
               handleNewSession rather than linking straight to /chat/new, so a
               click resets the open chat and closes the mobile sheet exactly
               like the New button does.

               A plain <button>, not our Button: the latter's base classes force
               every child svg to size-4, which would shrink the wordmark to a
               16px box. px-1 and -ml-1 cancel out, so the hover box gains some
               breathing room without shifting the mark off the header gutter. */
            <button
              type="button"
              onClick={handleNewSession}
              aria-label={`${APP_TITLE}, new chat`}
              className="-ml-1 flex items-center gap-0 rounded-md px-1 py-1 transition-colors hover:bg-accent outline-none focus-visible:ring-[3px] focus-visible:ring-ring/50 dark:bg-[hsl(220_23%_97%)] dark:hover:bg-[hsl(216_22%_85%)]"
            >
              <Image
                src={diceIcon}
                alt=""
                className="h-12 w-auto shrink-0"
                priority
              />
              <DataAgentWordmark className="-ml-2 h-5 w-auto shrink-0 text-heading-foreground dark:text-[hsl(218_14%_8%)]" />
            </button>
          )}

          <TooltipProvider>
            <Tooltip>
              <TooltipTrigger asChild>
                <Button
                  variant="ghost"
                  size="icon"
                  onClick={() => toggleCollapsed()}
                  className="h-10 w-10 hover:bg-accent text-foreground"
                >
                  {isCollapsed ? (
                    <PanelLeft className="h-4 w-4" />
                  ) : (
                    <PanelLeft className="h-4 w-4" />
                  )}
                </Button>
              </TooltipTrigger>
              <TooltipContent side={isCollapsed ? "right" : "bottom"}>
                <p>{isCollapsed ? "Open sidebar" : "Close sidebar"}</p>
              </TooltipContent>
            </Tooltip>
          </TooltipProvider>
        </div>

        {!isCollapsed && (
          <Button
            variant="ghost"
            onClick={handleNewSession}
            className="w-full justify-start mb-2 hover:bg-accent text-muted-foreground"
          >
            <Plus className="h-4 w-4 mr-2" />
            New
          </Button>
        )}

        {!isCollapsed &&
          (isSearchActive ? (
            <div className="relative">
              <Search className="absolute left-3 top-1/2 transform -translate-y-1/2 h-4 w-4 text-slate-400" />
              <Input
                autoFocus
                placeholder="Search"
                value={searchQuery}
                onChange={(e) => setSearchQuery(e.target.value)}
                onBlur={() => {
                  if (!searchQuery) setIsSearchActive(false);
                }}
                className="pl-11 border-0 bg-transparent shadow-none text-muted-foreground placeholder:text-muted-foreground focus-visible:ring-0 focus-visible:border-0"
              />
            </div>
          ) : (
            <Button
              variant="ghost"
              onClick={() => setIsSearchActive(true)}
              className="w-full justify-start hover:bg-accent text-muted-foreground"
            >
              <Search className="h-4 w-4 mr-2" />
              Search
            </Button>
          ))}
      </div>

      {/* Sessions list */}
      {/* min-h-0 so a long session list scrolls rather than growing the
          column and pushing the account row off the bottom. */}
      <ScrollArea className="flex-1 min-h-0 [&>div>div]:!block [&>div>div]:!min-w-0">
        <div className="p-2">
          {isCollapsed ? (
            <div className="space-y-2">
              <TooltipProvider>
                <Tooltip>
                  <TooltipTrigger asChild>
                    <Button
                      variant="ghost"
                      size="icon"
                      onClick={handleNewSession}
                      className="w-10 h-10 -translate-y-0.5 hover:bg-accent text-foreground"
                    >
                      <Plus className="h-4 w-4" />
                    </Button>
                  </TooltipTrigger>
                  <TooltipContent side="right">
                    <p>New Chat</p>
                  </TooltipContent>
                </Tooltip>
              </TooltipProvider>
            </div>
          ) : (
            <div className="space-y-1">
              {filteredSessions.length === 0 ? (
                <div className="text-center py-12">
                  <MessageSquare
                    className="w-10 h-10 text-muted-foreground mx-auto mb-3"
                    strokeWidth={1}
                  />
                  <p className="text-muted-foreground text-sm">
                    {searchQuery
                      ? "No conversations found"
                      : "No conversations yet"}
                  </p>
                </div>
              ) : (
                <div className="mb-4">
                  <div className="px-2 py-1 mb-2">
                    <h3 className="text-xs font-medium text-muted-foreground uppercase tracking-wider">
                      Recents
                    </h3>
                  </div>

                  <div className="space-y-1">
                    {filteredSessions.map((session) => {
                      const isRenaming = renamingId === session.id;

                      return (
                        <div key={session.id} className="relative group">
                          <div
                            className={`
                            rounded-lg p-2 transition-all duration-200
                            ${isRenaming ? "" : "cursor-pointer hover:bg-accent"}
                            ${
                              currentSessionId === session.id
                                ? "bg-selected"
                                : "hover:shadow-sm"
                            }
                            `}
                            onClick={() => {
                              if (!isRenaming) handleSessionClick(session);
                            }}
                          >
                            <div className="flex items-center justify-between">
                              <div className="flex-1 min-w-0">
                                {isRenaming ? (
                                  <input
                                    ref={renameInputRef}
                                    autoFocus
                                    value={renameValue}
                                    onChange={(e) =>
                                      setRenameValue(e.target.value)
                                    }
                                    onKeyDown={handleRenameKeyDown}
                                    onBlur={() => handleRenameBlur(session)}
                                    onClick={(e) => e.stopPropagation()}
                                    aria-label="Rename chat"
                                    /* Selection colours borrowed from the
                                       Input component, so the preselected
                                       title reads clearly in both themes. */
                                    className="w-full bg-transparent text-sm font-medium leading-tight text-foreground outline-none selection:bg-primary selection:text-primary-foreground"
                                  />
                                ) : (
                                  <p
                                    className={`text-sm truncate leading-tight ${
                                      currentSessionId === session.id
                                        ? "text-selected-foreground font-semibold"
                                        : "text-muted-foreground font-medium"
                                    }`}
                                  >
                                    {session.title}
                                  </p>
                                )}
                              </div>

                              <DropdownMenu
                                onOpenChange={(open) =>
                                  setOpenMenuId(open ? session.id : null)
                                }
                              >
                                <DropdownMenuTrigger asChild>
                                  <Button
                                    variant="ghost"
                                    size="icon"
                                    className={`h-6 w-6 transition-opacity text-foreground hover:bg-accent hover:text-foreground data-[state=open]:text-foreground ${
                                      openMenuId === session.id
                                        ? "opacity-100"
                                        : "opacity-0 group-hover:opacity-100"
                                    }`}
                                    onClick={(e) => e.stopPropagation()}
                                  >
                                    <MoreVertical className="h-3 w-3" />
                                  </Button>
                                </DropdownMenuTrigger>
                                <DropdownMenuContent
                                  align="end"
                                  className="w-48 border-0 shadow-none bg-input dark:bg-zinc-800"
                                  onCloseAutoFocus={(event) => {
                                    if (!renameStartedRef.current) return;
                                    renameStartedRef.current = false;
                                    event.preventDefault();
                                  }}
                                >
                                  <DropdownMenuItem
                                    onClick={(e) => handleCopy(e, session)}
                                    className="text-sm"
                                  >
                                    <Copy className="h-4 w-4 mr-2" />
                                    Copy
                                  </DropdownMenuItem>
                                  <DropdownMenuItem
                                    onClick={(e) => startRename(e, session)}
                                    className="text-sm"
                                  >
                                    <Pencil className="h-4 w-4 mr-2" />
                                    Rename
                                  </DropdownMenuItem>
                                  <DropdownMenuItem
                                    onClick={(e) =>
                                      handleDeleteSession(e, session.id)
                                    }
                                    className="text-red-400 focus:text-red-400 text-sm"
                                  >
                                    <Trash2 className="h-4 w-4 mr-2 text-red-400" />
                                    Delete
                                  </DropdownMenuItem>
                                </DropdownMenuContent>
                              </DropdownMenu>
                            </div>
                          </div>
                        </div>
                      );
                    })}
                  </div>
                </div>
              )}
            </div>
          )}
        </div>
      </ScrollArea>

      {/* Account. The avatar sits in its own 40px slot - the same footprint as
          the collapsed icon buttons - so it holds the x-axis of the New and
          open-sidebar icons whether the sidebar is open or closed. The rule on
          top is the sidebar's own edge colour, turned through 90 degrees. */}
      <div className="border-t border-sidebar-border px-2 py-2">
        <DropdownMenu>
          <DropdownMenuTrigger asChild>
            <Button
              variant="ghost"
              title={userId ?? undefined}
              /* No focus ring - --ring is blue in light, and the theme toggle
                 and the search field both drop it. The accent fill stands in,
                 so keyboard focus still shows. */
              className="w-full h-10 gap-0 px-0 justify-start rounded-lg overflow-hidden hover:bg-accent focus-visible:ring-0 focus-visible:border-0 focus-visible:bg-accent"
            >
              <span className="flex h-10 w-10 shrink-0 items-center justify-center">
                <span className="flex h-8 w-8 items-center justify-center rounded-full bg-input text-sm font-semibold text-foreground">
                  {userInitial}
                </span>
              </span>
              {!isCollapsed && (
                /* The New button clears 16px between its icon and its label
                   (the button's gap-2 plus the icon's mr-2). Centring the
                   32px circle in the 40px slot already leaves 4px of that. */
                <span className="ml-3 truncate pr-3 text-sm font-medium text-muted-foreground">
                  {userId}
                </span>
              )}
            </Button>
          </DropdownMenuTrigger>
          <DropdownMenuContent
            side="top"
            align="start"
            /* w-72 less the px-2 gutters: the width of the account row when
               the sidebar is open. Fixed rather than measured off the
               trigger, so a collapsed sidebar opens the same menu. */
            className="w-[17rem] border-0 shadow-none bg-input dark:bg-zinc-800"
          >
            <DropdownMenuItem
              onClick={handleLogout}
              className="text-sm text-muted-foreground"
            >
              <LogOut className="h-4 w-4 mr-2" />
              Log out
            </DropdownMenuItem>
          </DropdownMenuContent>
        </DropdownMenu>
      </div>
    </div>
  );

  return (
    <>
      {/* Desktop Sidebar */}
      <div className={`hidden md:block h-full ${className}`}>
        <div
          className={`h-full border-r border-sidebar-border transition-all duration-300 ${
            isCollapsed ? "w-14" : "w-72"
          }`}
        >
          <div className="h-full relative">{SidebarContent()}</div>
        </div>
      </div>

      {/* Mobile Sidebar */}
      <div className="md:hidden">
        <Sheet open={isMobileOpen} onOpenChange={setIsMobileOpen}>
          <SheetTrigger asChild>
            <Button
              variant="outline"
              size="icon"
              className="fixed top-4 left-4 z-50 bg-card/80 backdrop-blur-sm"
            >
              <MessageSquare className="h-4 w-4" />
            </Button>
          </SheetTrigger>
          <SheetContent side="left" className="w-72 p-0">
            {SidebarContent()}
          </SheetContent>
        </Sheet>
      </div>
    </>
  );
}
